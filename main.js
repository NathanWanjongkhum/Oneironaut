ASSET_MANAGER.downloadAll(() => {
	PARAMS.BITWIDTH = 32;
	PARAMS.SCALE = 1;
	PARAMS.BLOCKWIDTH = PARAMS.BITWIDTH * PARAMS.SCALE;

	const canvas = document.getElementById("gameWorld");
	const ctx = canvas.getContext("2d");

	PARAMS.CANVAS_WIDTH = canvas.width;
	PARAMS.CANVAS_HEIGHT = canvas.height;
	PARAMS.DEBUG = true;

	gameEngine.init(ctx);


	// gameEngine.buildWorld();

	gameEngine.restartToGameplay = () => gameEngine.resetWorld("gameplay");
	gameEngine.restartToMenu = () => gameEngine.resetWorld("menu");
	gameEngine.startLevel = (levelId) => gameEngine.resetWorld("gameplay", levelId);

	//Initialize menu managers
	gameEngine.menuRoomController = new MenuRoomController(gameEngine);
	gameEngine.endGame = new EndGame(gameEngine);

	//Initialize other engine components
	gameEngine.camera = new Camera(gameEngine);
	gameEngine.bg = new Background(gameEngine);

	// Start engine loop
	gameEngine.start();

	// Start music after any user interaction
	canvas.addEventListener("pointerdown", Music.tryStartMusic);

	window.addEventListener("keydown", (e) => {
		if (!gameEngine.gameOver) return;
		if (e.key === "r" || e.key === "R") gameEngine.restartToGameplay();
		if (e.key === "Escape") gameEngine.restartToMenu();
	});


	Music.init();
	if (window.setMusicMode) window.setMusicMode("menu");

	// tryStart once (prevents repeated calls)
	canvas.addEventListener("pointerdown", () => Music.tryStart(), { once: true });

});

